import re
import string

def clean_text(text):
    """
    This function cleans raw text by lowering it, removing punctuation,
    removing extra spaces, and handling basic formatting issues.
    """
    # 1. Convert to lowercase
    text = text.lower()

    # 2. Remove punctuation and special characters
    text = text.translate(str.maketrans('', '', string.punctuation))

    # 3. Remove any carriage returns or tab characters and replace with space
    text = re.sub(r'\s+', ' ', text)

    # 4. Remove leading and trailing spaces
    text = text.strip()

    return text

# Let's test this function on a tiny sample before applying it to all 39,103 articles
