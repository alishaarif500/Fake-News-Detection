def predict_news_interactively(custom_text):
    """
    Cleans, vectorizes, and predicts whether a given raw text string
    is Real News or Fake News using both trained models.
    """
    # 1. Apply the exact same cleaning function used in training
    cleaned = clean_text(custom_text)

    # 2. Vectorize the cleaned text using our trained vectorizer
    vectorized_text = vectorizer.transform([cleaned])

    # 3. Predict with Logistic Regression
    lr_prediction = lr_model.predict(vectorized_text)[0]
    lr_proba = lr_model.predict_proba(vectorized_text)[0][lr_prediction] * 100
    lr_label = "Fake News (1)" if lr_prediction == 1 else "Real News (0)"

    # 4. Predict with Naive Bayes
    nb_prediction = nb_model.predict(vectorized_text)[0]
    nb_proba = nb_model.predict_proba(vectorized_text)[0][nb_prediction] * 100
    nb_label = "Fake News (1)" if nb_prediction == 1 else "Real News (0)"

    # 5. Display the output cleanly
    print("=" * 70)
    print(f"Raw News Text Preview: \"{custom_text[:120]}...\"")
    print("=" * 70)
    print(f"[Logistic Regression Prediction] -> {lr_label} ({lr_proba:.2f}% Confidence)")
    print(f"[Multinomial Naive Bayes]        -> {nb_label} ({nb_proba:.2f}% Confidence)")
    print("=" * 70 + "\n")

