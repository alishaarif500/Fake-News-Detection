from sklearn.model_selection import train_test_split

# Features (X) will be our preprocessed clean text column
X = df['clean_text']
# Target (y) is the label (0 = Real, 1 = Fake)
y = df['label']

# Split into 80% training and 20% testing sets
# stratify=y ensures both sets have the same percentage of real/fake news
X_train, X_test, y_train, y_test = train_test_split(
    X, y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("--- Data Split Successful! ---")
print(f"Training set size (X_train): {len(X_train)} samples")
print(f"Testing set size (X_test):  {len(X_test)} samples")
print(f"Total unique items:          {len(X_train) + len(X_test)}")

print("\n--- Training Class Distribution (%) ---")
print(y_train.value_counts(normalize=True) * 100)

print("\n--- Testing Class Distribution (%) ---")
print(y_test.value_counts(normalize=True) * 100)

from sklearn.feature_extraction.text import TfidfVectorizer

print("Converting text to TF-IDF features... (This may take a few seconds)")

# Initialize the TF-IDF Vectorizer
# We filter out standard English stop words ('and', 'the', etc.)
vectorizer = TfidfVectorizer(stop_words='english', max_features=10000)

# Learn the vocabulary and transform the training data
X_train_tfidf = vectorizer.fit_transform(X_train)

# Transform the testing data (using the vocabulary learned from training only)
X_test_tfidf = vectorizer.transform(X_test)

print("Feature extraction complete!")
print(f"Training features shape: {X_train_tfidf.shape}")
print(f"Testing features shape:  {X_test_tfidf.shape}")

from sklearn.linear_model import LogisticRegression

print("Training the Logistic Regression model... (This should take under 10 seconds)")

# Initialize the model
lr_model = LogisticRegression(max_iter=1000, random_state=42)

# Train (fit) the model on our training TF-IDF vectors
lr_model.fit(X_train_tfidf, y_train)

print("Model training complete!")

# Generate predictions on the test set
y_pred_lr = lr_model.predict(X_test_tfidf)
print(f"Successfully generated predictions for {len(y_pred_lr)} test articles.")

